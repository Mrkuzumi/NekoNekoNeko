/*任务描述
本关任务：将给定 n×n 方阵中的每个元素循环向右移 m 个位置，即将第 0、1、⋯、n−1 列变换为第 n−m、n−m+1、⋯、n−1、0、1、⋯、n−m−1 列。

编程要求
根据提示，在右侧编辑器补充代码，将给定 n×n 方阵中的每个元素循环向右移 m 个位置。

测试说明
输入说明：
输入第一行给出两个正整数m和n（1≤n≤6）。接下来一共n行，每行n个整数，表示一个n阶的方阵。

输出说明：
按照输入格式输出移动后的方阵：即输出n行，每行n个整数，每个整数后输出一个空格。

平台会对你编写的代码进行测试：

测试输入：
2 3
1 2 3
4 5 6
7 8 9

预期输出：
2 3 1
5 6 4
8 9 7

提示
请注意 m 有可能大于 n。*/
#include <stdio.h>

int main()
{
    int m, n;
    // 输入位移次数 m 和方阵阶数 n
    if (scanf("%d %d", &m, &n) != 2)
        return 0;

    int a[6][6]; // 根据题意 1 <= n <= 6
    for (int i = 0; i < n; i++)
    {
        for (int j = 0; j < n; j++)
        {
            scanf("%d", &a[i][j]);
        }
    }

    // 考虑到 m 可能大于 n，先取模
    m = m % n;

    for (int i = 0; i < n; i++)
    {
        for (int j = 0; j < n; j++)
        {
            // 计算右移后当前位置 (i, j) 对应的原矩阵列下标
            // 原列下标 = (新下标 - 位移 + n) % n
            int old_j = (j - m + n) % n;
            printf("%d ", a[i][old_j]);
        }
        printf("\n");
    }

    return 0;
}
